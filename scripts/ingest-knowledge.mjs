/**
 * Builds the portfolio assistant's knowledge base from src/data/portfolioData.js
 * and syncs it to Supabase.
 *
 *   npm run ingest:preview   Write the chunks to knowledge-preview.md for review. No API calls.
 *   npm run ingest           Embed new or changed chunks, upsert them, delete removed ones.
 *
 * Re-running is safe: chunks keep stable ids, and a chunk whose text (and
 * embedding model) hasn't changed is not embedded again.
 *
 * Reads GEMINI_API_KEY, NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY
 * from .env.local (loaded by the npm script). Prints no secrets.
 */

import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { createClient } from "@supabase/supabase-js";

import * as portfolio from "../src/data/portfolioData.js";
import { GeminiError, embedTexts, geminiConfig } from "../src/lib/ai/gemini.js";
import { UNCONFIRMED_PROJECT_IDS, buildKnowledgeChunks } from "../src/lib/rag/knowledge.js";

const TABLE = "knowledge_chunks";
const PREVIEW_FILE = fileURLToPath(new URL("../knowledge-preview.md", import.meta.url));

const args = new Set(process.argv.slice(2));
const dryRun = args.has("--dry-run");
const force = args.has("--force"); // re-embed everything (e.g. after changing the model)

class IngestError extends Error {}

/**
 * Stop with a message. Throws instead of calling process.exit(), which on
 * Windows can abort while network handles are still closing.
 * @param {string} message
 * @returns {never}
 */
function fail(message) {
  throw new IngestError(message);
}

async function main() {
  const chunks = buildKnowledgeChunks(portfolio);
  const ids = new Set(chunks.map((chunk) => chunk.id));
  if (ids.size !== chunks.length) fail("Two knowledge chunks share an id. Check for duplicate project ids in portfolioData.js.");

  console.log(`Built ${chunks.length} knowledge chunks from src/data/portfolioData.js.`);
  if (UNCONFIRMED_PROJECT_IDS.length) {
    console.log(`Held back as "details being confirmed": ${UNCONFIRMED_PROJECT_IDS.join(", ")}.`);
  }

  if (dryRun) {
    const body = chunks
      .map((chunk) => `## ${chunk.title}\n\n\`${chunk.id}\` · ${chunk.category} · ${chunk.docType} · panel: ${chunk.section}\n\n\`\`\`text\n${chunk.content}\n\`\`\``)
      .join("\n\n");
    await writeFile(
      PREVIEW_FILE,
      `# Knowledge base preview\n\nGenerated by \`npm run ingest:preview\`. This is exactly what the assistant can draw on. Nothing was uploaded.\n\n${body}\n`,
      "utf8"
    );
    console.log(`Preview written to knowledge-preview.md. Nothing was uploaded.`);
    return;
  }

  const config = geminiConfig();
  if (!config.apiKey) fail("GEMINI_API_KEY is missing from .env.local.");
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) fail("NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY must be set in .env.local.");

  const supabase = createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });

  const hashOf = (/** @type {string} */ content) =>
    createHash("sha256").update(`${config.embeddingModel}\n${config.dimensions}\n${content}`).digest("hex");

  // What is stored already?
  const { data: existing, error: readError } = await supabase.from(TABLE).select("id, content_hash");
  if (readError) {
    fail(
      /permission denied/i.test(readError.message)
        ? `Could not read the ${TABLE} table: ${readError.message}. Check that SUPABASE_SERVICE_ROLE_KEY is the secret key, and run the latest supabase/migrations/001_knowledge_chunks.sql again (it grants the server role access).`
        : `Could not read the ${TABLE} table: ${readError.message}. Has supabase/migrations/001_knowledge_chunks.sql been run?`
    );
  }
  const storedHash = new Map((existing ?? []).map((row) => [row.id, row.content_hash]));

  const changed = chunks.filter((chunk) => force || storedHash.get(chunk.id) !== hashOf(chunk.content));
  const removed = [...storedHash.keys()].filter((id) => !ids.has(id));
  console.log(`${changed.length} new or changed, ${chunks.length - changed.length} unchanged, ${removed.length} to remove.`);

  if (changed.length) {
    console.log(`Embedding with ${config.embeddingModel} (${config.dimensions} dimensions)…`);
    const vectors = await embedTexts(
      config,
      changed.map((chunk) => ({ text: chunk.content, title: chunk.title })),
      "document",
      { timeoutMs: 60000 }
    );
    const rows = changed.map((chunk, index) => ({
      id: chunk.id,
      category: chunk.category,
      doc_type: chunk.docType,
      title: chunk.title,
      section: chunk.section,
      content: chunk.content,
      content_hash: hashOf(chunk.content),
      embedding_model: config.embeddingModel,
      embedding: vectors[index],
      metadata: chunk.metadata,
      updated_at: new Date().toISOString(),
    }));
    const { error: upsertError } = await supabase.from(TABLE).upsert(rows, { onConflict: "id" });
    if (upsertError) fail(`Saving chunks failed: ${upsertError.message}`);
  }

  if (removed.length) {
    const { error: deleteError } = await supabase.from(TABLE).delete().in("id", removed);
    if (deleteError) fail(`Removing outdated chunks failed: ${deleteError.message}`);
    console.log(`Removed: ${removed.join(", ")}`);
  }

  console.log("✓ Knowledge base is up to date.");
}

main().catch((error) => {
  const message =
    error instanceof GeminiError
      ? `${error.message}${error.detail ? `: ${error.detail}` : ""}`
      : error instanceof Error
        ? error.message
        : String(error);
  console.error(`\n✗ ${message}`);
  process.exitCode = 1;
});
